# The verbatim schema-reference body. A single source of truth rendered byte-for-byte, so the drift gate
# and the fail-close sweep cover the adopter-facing schema. Sentence-cased, no en or em dashes.
_SCHEMA_BODY = '''# AIQT Guardrails: adopter crosswalk schema reference (VER-CORE 8.x)
# GENERATED by tools/gen_crosswalk.py; do not hand-edit. This file DOCUMENTS the schema of the runtime
# adopter file .aiqt/migration/crosswalk.toml; it is not itself a crosswalk. The runtime crosswalk is
# adopter-state (never a manifest set-equality member). Every verdict field is HUMAN-JUDGMENT: the
# check_crosswalk gate proves the fields are present, well-formed, and name a distinct reviewer and a
# distinct family, never that a real cross-family review occurred.
schema-version = 1

# [target-release]: the release the migration maps TO (the pinned successor inventory).
#   version, tag-object-sha, commit-sha, root, clause-inventory-digest

# [[archive-file]]: one row per archived legacy file (immutable, 8.2).
#   legacy-path, archive-sha256 (also the archive directory name), size, owner,
#   predecessor-clause-ids (the predecessor ids segmented out of this archived file)

# [enumeration-review]: 8.2 completeness attestation (HUMAN-JUDGMENT).
#   enumerator, enumerator-family, verdict = "complete", rationale,
#   reviewer (MUST differ from enumerator), reviewer-family, reviewed-utc

# [[predecessor]]: mirrors the 7.2 clause-inventory row over the ARCHIVED file (8.2 lines 1164 to 1168).
#   clause-id (the 8.3 pre-<archive-hash-prefix>.<ordinal> namespace, unpadded), archive-sha256,
#   start-line, end-line, canonical-text, source-digest (= the whole archived file's archive-sha256)

# [[mapping]]: one row PER successor, folds and splits included (8.6 lines 1223 to 1226).
#   predecessor-clause-id, successor-clause-id, successor-quote (a verbatim contiguous substring of the
#   successor clause's canonical text, 8.4), author, author-family,
#   semantic-verdict = "equal-or-stronger", rationale,
#   reviewer (MUST differ from author; family MUST differ), reviewer-family, reviewed-utc

# [[pointer-hint]]: an in-file pointer mirrored for the reviewer; a hint only, zero evidentiary weight.
#   predecessor-clause-id, expected-successor-ids, coverage, carrier = "frontmatter" | "body"

# Section 8.6 pointer-carriage deferral (D10): this tool does not claim section 8.6 pointer-carriage
# conformance; migration-state pointer carriage is deferred out of the VC-6 slice (to Step 7). A pointer
# here is an incidental in-file hint, not the spec's migration-state pointer.
'''

# Pointer grammar (8.6 lines 1206 to 1210): greppable hints carried in frontmatter or body.
_EXPECTED_RE = re.compile(r"Expected-successor:\s*(.+)")
_COVERAGE_RE = re.compile(r"Coverage:\s*(.+)")
def _segment_paragraphs(text):
    """Segment text into (paragraph_text, start_line, end_line) blocks on blank-line boundaries, tracking
    1-based line numbers, so each candidate predecessor row can carry a tight 7.2 whole-line source span
    (start-line/end-line) over the archived bytes. Blank (whitespace-only) lines delimit; a paragraph is a
    maximal run of non-blank lines. An all-blank or empty file yields a single whole-file block."""
    lines = text.split("\n")
    blocks, i, nlines = [], 0, len(lines)
    while i < nlines:
        while i < nlines and lines[i].strip() == "":
            i += 1
        if i >= nlines:
            break
        start = i
        while i < nlines and lines[i].strip() != "":
            i += 1
        blocks.append(("\n".join(lines[start:i]), start + 1, i))   # end-line = i (1-based inclusive)
    if not blocks:
        return [(text, 1, max(1, nlines))]
    return blocks


def render_schema():
    return _SCHEMA_BODY


def run_repo(root, check):
    if not check:
        (root / SCHEMA_REL).parent.mkdir(parents=True, exist_ok=True)
    drifted = reconcile(root / SCHEMA_REL, render_schema(), check)   # fail-closes (exit 2) on I/O error
    if not check:
        print("wrote {}".format(SCHEMA_REL))
        return 0
    if drifted:
        print("drift: {} is out of date; run tools/gen_crosswalk.py".format(SCHEMA_REL), file=sys.stderr)
        return 1
    return 0


# --- adopter mode: archive-first candidate generation -------------------------------------------------

class AdoptError(Exception):
    """A refused adopter precondition or an archive immutability/read-safety violation: fail-closed. The
    exit_code is 1 for a refused precondition (a human-actionable input state) and 2 for malformed or
    unsafe input, an I/O error, or an unconfirmed durability guarantee."""

    def __init__(self, message, exit_code=2):
        super().__init__(message)
        self.exit_code = exit_code


def _toml_str(value):
    return '"' + value.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n") + '"'


def _open_dir_at(dir_fd, name, create):
    """G8/G9: open directory `name` beneath dir_fd through an O_DIRECTORY|O_NOFOLLOW handle so a symlinked
    component can never redirect the archive out of the tree, creating it first when `create`. When a new
    directory is created its parent (dir_fd) is fsynced so a crash cannot lose the just-created entry (G9),
    and a fsync failure is PROPAGATED as an AdoptError rather than swallowed (success is never reported on
    an unconfirmed durability guarantee). Returns the opened dir fd (caller closes). AdoptError on a
    symlinked component, a non-directory, an I/O error, or an unconfirmed fsync."""
    created = False
    if create:
        try:
            os.mkdir(name, dir_fd=dir_fd)
            created = True
        except FileExistsError:
            pass
        except OSError as exc:
            raise AdoptError("cannot create archive component {!r} ({}); fail-closed".format(name, exc))
    try:
        fd = os.open(name, os.O_RDONLY | os.O_DIRECTORY | os.O_NOFOLLOW, dir_fd=dir_fd)
    except OSError as exc:
        raise AdoptError("cannot open archive component {!r} through a no-follow handle ({}); a symlinked "
                         "component is refused".format(name, exc))
    if created:
        try:
            os.fsync(dir_fd)                              # G9: persist the newly-created directory entry
        except OSError as exc:
            os.close(fd)
            raise AdoptError("cannot fsync the parent after creating {!r} ({}); durability not confirmed, "
                             "fail-closed".format(name, exc))
    return fd


def _walk_components(base_fd, names, create):
    """G8/G9: descend `names` in turn beneath base_fd, every hop through _open_dir_at (O_NOFOLLOW per
    component, durable creation), so no symlinked ANCESTOR can redirect the path and each new directory is
    crash-durable. Returns the final dir fd; intermediate fds are closed and base_fd is left open.
    AdoptError (fail-closed) on any symlinked or unconfirmed component."""
    fd, close_prev = base_fd, False
    try:
        for name in names:
            nxt = _open_dir_at(fd, name, create)
            if close_prev:
                os.close(fd)
            fd, close_prev = nxt, True
    except BaseException:
        if close_prev:
            os.close(fd)
        raise
    return fd


def _read_payload_fd(entry_fd):
    """G8 (8.2): read the `payload` beneath entry_fd through a NO-FOLLOW handle and require a REGULAR file,
    so an archive immutability comparison can never read redirectable external bytes. Returns the payload
    bytes, or None when the payload is absent; AdoptError on a symlinked or non-regular payload."""
    try:
        pfd = os.open("payload", os.O_RDONLY | os.O_NOFOLLOW, dir_fd=entry_fd)
    except FileNotFoundError:
        return None
    except OSError as exc:
        raise AdoptError("cannot open archived payload ({}); a symlinked payload is refused".format(exc))
    try:
        if not stat.S_ISREG(os.fstat(pfd).st_mode):
            raise AdoptError("archived payload is not a regular file")
        return _read_fd_all(pfd)
    finally:
        os.close(pfd)


_TMP_SEQ = itertools.count()


def _verify_published_payload(entry_fd, digest, tmp_stat):
    """G8: re-open the just-published `payload` beneath entry_fd through a NO-FOLLOW handle and confirm it is
    the SAME regular-file inode we wrote (st_dev/st_ino match the retained temp) whose bytes still hash to
    `digest`, BEFORE reporting success. So a concurrent writer who swaps the temp pathname for a symlink,
    or substitutes the payload between the write and the publish, fails closed rather than publishing a
    redirected or altered inode. AdoptError on a symlinked, non-regular, substituted, or mismatched payload."""
    try:
        pfd = os.open("payload", os.O_RDONLY | os.O_NOFOLLOW, dir_fd=entry_fd)
    except OSError as exc:
        raise AdoptError("cannot re-open the published payload through a no-follow handle ({}); a symlinked "
                         "payload is refused".format(exc))
    try:
        st = os.fstat(pfd)
        if not stat.S_ISREG(st.st_mode):
            raise AdoptError("published payload {}/payload is not a regular file".format(digest))
        if (st.st_dev, st.st_ino) != (tmp_stat.st_dev, tmp_stat.st_ino):
            raise AdoptError("published payload {}/payload is not the inode we wrote (concurrent substitution)"
                             .format(digest))
        if hashlib.sha256(_read_fd_all(pfd)).hexdigest() != digest:
            raise AdoptError("published payload {}/payload does not hash to its digest".format(digest))
    finally:
        os.close(pfd)


def _write_payload(entry_fd, digest, data):
    """Publish `data` as `payload` beneath entry_fd: write a UNIQUE-per-call temp (O_CREAT|O_EXCL|O_NOFOLLOW,
    so concurrent callers never share a name), fsync it, then publish by a NO-OVERWRITE, NO-FOLLOW link
    (os.link fails if payload already exists; follow_symlinks=False so a temp pathname a concurrent writer
    swapped for a symlink links the link itself, refused below, never its target inode), so a publish race
    COMPARES bytes and accepts only byte-equality rather than overwriting an already-published payload. On
    the winning branch the published payload is re-verified at source (same inode as the retained temp, same
    digest) before success is reported. The temp is always unlinked; entry_fd is fsynced so the published
    payload entry is durable. Every handle is dir_fd-relative and O_NOFOLLOW (G8)."""
    tmp_name = "payload.{}.{}.tmp".format(os.getpid(), next(_TMP_SEQ))
    tfd = os.open(tmp_name, os.O_WRONLY | os.O_CREAT | os.O_EXCL | os.O_NOFOLLOW, 0o600, dir_fd=entry_fd)
    try:
        with os.fdopen(tfd, "wb") as fh:
            fh.write(data)
            fh.flush()
            os.fsync(fh.fileno())                         # temp bytes durable BEFORE the atomic publish
            tmp_stat = os.fstat(fh.fileno())              # retain the temp inode BEFORE the fd closes
        try:
            os.link(tmp_name, "payload", src_dir_fd=entry_fd, dst_dir_fd=entry_fd,
                    follow_symlinks=False)                # no-overwrite, no-follow publish
        except FileExistsError:                           # lost a publish race: accept only byte-equality
            existing = _read_payload_fd(entry_fd)         # G8: no-follow read of the winner's payload
            if existing is None or existing != data:
                raise AdoptError("archive immutability violation: {}/payload already holds different bytes"
                                 .format(digest))
        else:                                             # we published: re-verify the linked payload at source
            _verify_published_payload(entry_fd, digest, tmp_stat)
    finally:
        try:
            os.unlink(tmp_name, dir_fd=entry_fd)
        except FileNotFoundError:
            pass
    os.fsync(entry_fd)                                    # durable published-payload directory entry


def archive_file(archive_fd, data):
    """Archive raw bytes as <archive_fd>/<sha256>/payload, immutably, ENTIRELY through dir_fd-relative
    O_NOFOLLOW handles beneath archive_fd (opened by run_adopter via a no-follow ANCESTOR walk), so neither
    a symlinked ancestor (.aiqt, archive) nor a symlinked hash-entry or payload can redirect the archive in
    or out of the tree (G8). Returns the sha256. Refuses (AdoptError) if an existing entry under the same
    hash holds DIFFERING bytes (8.2 immutability); an identical re-archive is idempotent. Content-addressing
    keeps the archive idempotent (identical bytes yield the same hash directory, so two writers of the same
    payload cannot disagree). The hash directory is created durably (G9) and the payload is published by a
    no-overwrite link (see _write_payload), so an existence race COMPARES bytes and accepts only
    byte-equality rather than overwriting an already-published payload."""
    digest = hashlib.sha256(data).hexdigest()
    try:
        entry_fd = os.open(digest, os.O_RDONLY | os.O_DIRECTORY | os.O_NOFOLLOW, dir_fd=archive_fd)
    except FileNotFoundError:
        entry_fd = _open_dir_at(archive_fd, digest, create=True)  # mkdir + no-follow open + parent fsync (G8/G9)
    except OSError as exc:
        raise AdoptError("cannot open archive entry {} through a no-follow handle ({}); a symlinked entry "
                         "is refused".format(digest, exc))
    try:
        existing = _read_payload_fd(entry_fd)             # G8: no-follow payload read; None when absent
        if existing is not None:
            if existing != data:
                raise AdoptError("archive immutability violation: {}/payload already holds different bytes"
                                 .format(digest))
            os.fsync(entry_fd)                            # fix #7: durable on the idempotent early-exists return
            return digest
        _write_payload(entry_fd, digest, data)
        return digest
    finally:
        os.close(entry_fd)


def _read_fd_all(fd):
    chunks = []
    while True:
        block = os.read(fd, 1 << 20)
        if not block:
            break
        chunks.append(block)
    return b"".join(chunks)


def parse_pointers(text):
    """Extract (expected_successor_ids, coverage) pointer hints from a legacy file's text. A pointer is a
    HINT with zero evidentiary weight; an embedded pointer stays verbatim in the raw archived bytes, and
    the tool never INJECTS a parsed or derived pointer annotation into an archived payload."""
    expected = []
    for m in _EXPECTED_RE.finditer(text):
        expected += [tok.strip() for tok in re.split(r"[,\s]+", m.group(1).strip()) if tok.strip()]
    cov = ""
    mc = _COVERAGE_RE.search(text)
    if mc:
        cov = mc.group(1).strip()
    return expected, cov


def _rank_candidates(pred_text, successor_texts):
    """Deterministic lexical-overlap ranking of successor candidates for a predecessor paragraph. Pure
    attention-ordering; it never fills a verdict and never waives review."""
    pred_tokens = set(re.findall(r"[a-z0-9]+", pred_text.lower()))
    scored = []
    for sid, stext in sorted(successor_texts.items()):
        stoks = set(re.findall(r"[a-z0-9]+", stext.lower()))
        overlap = len(pred_tokens & stoks)
        scored.append((-overlap, sid))
    scored.sort()
    return [sid for _, sid in scored]


def build_candidates(legacy_root, archive_fd, successor_texts):
    """Archive every legacy file FIRST (beneath the no-follow-anchored archive_fd), then emit candidate
    predecessor rows, candidate mapping rows with EMPTY review fields, pointer hints, and the computed
    unmatched list. Deterministic ordering."""
    legacy_root = Path(legacy_root)
    files = sorted(p for p in legacy_root.rglob("*") if p.is_file())
    if not files:
        raise AdoptError("no legacy files under {}".format(legacy_root), exit_code=1)
    archive_rows, predecessor_rows, mapping_rows, pointer_rows = [], [], [], []
    for f in files:
        # fix #6: capture the 8.2 OWNER from the SAME opened source fd the raw bytes come from, so the
        # recorded owner cannot disagree with the archived payload. No O_NOFOLLOW here: legacy trees may
        # legitimately carry symlinked files that rglob(is_file) and the prior read_bytes both followed.
        fd = os.open(str(f), os.O_RDONLY)
        try:
            owner = os.fstat(fd).st_uid
            data = _read_fd_all(fd)                        # archive raw bytes FIRST (before any pointers)
        finally:
            os.close(fd)
        digest = archive_file(archive_fd, data)
        rel = str(f.relative_to(legacy_root))
        try:
            text = data.decode("utf-8")
        except UnicodeDecodeError:
            text = ""
        prefix = digest[:12]
        blocks = _segment_paragraphs(text)
        pred_ids = []
        for ordinal, (para, start_line, end_line) in enumerate(blocks, start=1):
            pid = "pre-{}.{}".format(prefix, ordinal)
            pred_ids.append(pid)
            # emit the computable 7.2 whole-line span (start-line/end-line) the schema documents, so a
            # candidate predecessor row is span-checkable rather than span-omitting.
            predecessor_rows.append({"clause-id": pid, "archive-sha256": digest, "start-line": start_line,
                                     "end-line": end_line, "canonical-text": para.strip(),
                                     "source-digest": digest})
            expected, coverage = parse_pointers(para)
            ranked = _rank_candidates(para, successor_texts)
            if expected or coverage:
                pointer_rows.append({"predecessor-clause-id": pid,
                                     "expected-successor-ids": expected, "coverage": coverage,
                                     "carrier": "body"})
            top = expected[:] if expected else ranked[:1]
            for sid in top:
                mapping_rows.append({"predecessor-clause-id": pid, "successor-clause-id": sid})
        archive_rows.append({"legacy-path": rel, "archive-sha256": digest, "size": len(data),
                             "owner": owner, "predecessor-clause-ids": pred_ids})
    mapped = {m["predecessor-clause-id"] for m in mapping_rows}
    all_pred = {r["clause-id"] for r in predecessor_rows}
    unmatched = sorted(all_pred - mapped)
    return {"archive": archive_rows, "predecessor": predecessor_rows, "mapping": mapping_rows,
            "pointer": pointer_rows, "unmatched": unmatched}


def render_candidates(cand):
    """Render candidate crosswalk material as deterministic TOML with EMPTY review/verdict fields, so a
    human reviewer fills the judgment and a gate never sees a machine-asserted verdict."""
    out = ["# GENERATED CANDIDATE crosswalk (tools/gen_crosswalk.py --legacy-root). Review fields are",
           "# intentionally EMPTY: a human reviewer supplies every verdict. This tool asserts NOTHING.",
           "schema-version = 1", ""]
    for r in cand["archive"]:
        out += ["[[archive-file]]", "legacy-path = {}".format(_toml_str(r["legacy-path"])),
                "archive-sha256 = {}".format(_toml_str(r["archive-sha256"])),
                "size = {}".format(r["size"]),
                "owner = {}".format(r["owner"]),
                "predecessor-clause-ids = [{}]".format(
                    ", ".join(_toml_str(x) for x in r["predecessor-clause-ids"])), ""]
    for r in cand["predecessor"]:
        out += ["[[predecessor]]", "clause-id = {}".format(_toml_str(r["clause-id"])),
                "archive-sha256 = {}".format(_toml_str(r["archive-sha256"])),
                "start-line = {}".format(r["start-line"]),
                "end-line = {}".format(r["end-line"]),
                "canonical-text = {}".format(_toml_str(r["canonical-text"])),
                "source-digest = {}".format(_toml_str(r["source-digest"])), ""]
    for r in cand["mapping"]:
        out += ["[[mapping]]", "predecessor-clause-id = {}".format(_toml_str(r["predecessor-clause-id"])),
                "successor-clause-id = {}".format(_toml_str(r["successor-clause-id"])),
                'successor-quote = ""', 'author = ""', 'author-family = ""',
                'semantic-verdict = ""', 'rationale = ""', 'reviewer = ""', 'reviewer-family = ""',
                'reviewed-utc = ""', ""]
    for r in cand["pointer"]:
        out += ["[[pointer-hint]]",
                "predecessor-clause-id = {}".format(_toml_str(r["predecessor-clause-id"])),
                "expected-successor-ids = [{}]".format(
                    ", ".join(_toml_str(x) for x in r["expected-successor-ids"])),
                "coverage = {}".format(_toml_str(r["coverage"])),
                "carrier = {}".format(_toml_str(r["carrier"])), ""]
    out += ["# unmatched predecessors (computed; every one needs a reviewed mapping before check_crosswalk",
            "# can pass): [{}]".format(", ".join(_toml_str(x) for x in cand["unmatched"]))]
    return "\n".join(out) + "\n"


def _write_candidate(migration_fd, text):
    """Write crosswalk.candidate.toml beneath migration_fd through an O_NOFOLLOW handle (G8, so a symlinked
    candidate file cannot redirect the write) and fsync both the file and the directory entry (G9)."""
    fd = os.open("crosswalk.candidate.toml",
                 os.O_WRONLY | os.O_CREAT | os.O_TRUNC | os.O_NOFOLLOW, 0o644, dir_fd=migration_fd)
    with os.fdopen(fd, "w", encoding="utf-8") as fh:
        fh.write(text)
        fh.flush()
        os.fsync(fh.fileno())
    os.fsync(migration_fd)


def run_adopter(legacy_root, out_dir, successor_texts):
    out_dir = Path(out_dir)
    try:
        os.makedirs(str(out_dir), exist_ok=True)          # the chosen output root is the trusted anchor
        root_fd = os.open(str(out_dir), os.O_RDONLY | os.O_DIRECTORY)
    except OSError as exc:
        print("error: cannot open output root {} ({}); fail-closed".format(out_dir, exc), file=sys.stderr)
        return 2
    try:
        # G8/G9: walk .aiqt/archive and .aiqt/migration beneath the output root through no-follow handles
        # (durable creation), so no symlinked ancestor can redirect the archive or the migration state, and
        # archive/publish everything beneath those anchored handles.
        archive_fd = _walk_components(root_fd, (".aiqt", "archive"), create=True)
        try:
            cand = build_candidates(legacy_root, archive_fd, successor_texts)
        finally:
            os.close(archive_fd)
        migration_fd = _walk_components(root_fd, (".aiqt", "migration"), create=True)
        try:
            _write_candidate(migration_fd, render_candidates(cand))
        finally:
            os.close(migration_fd)
    except AdoptError as exc:
        print("error: {}; fail-closed".format(exc), file=sys.stderr)
        return exc.exit_code
    finally:
        os.close(root_fd)
    print("wrote candidate crosswalk and {} archive entries under {}".format(
        len(cand["archive"]), out_dir))
    return 0


def main():
    args = sys.argv[1:]
    if "--self-test" in args:
        return self_test()
    if "--legacy-root" in args:
        legacy = Path(args[args.index("--legacy-root") + 1]).resolve()
        out = Path(args[args.index("--out") + 1]).resolve() if "--out" in args else legacy.parent
        return run_adopter(legacy, out, {})
    return run_repo(repo_root(), "--check" in args)


