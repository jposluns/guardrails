# Proves the generator's own invariants over synthetic trees:
#   (a) REPO mode generates the schema reference, then re-checks drift-clean and is deterministic;
#   (b) a mutated schema reference fails --check (exit 1);
#   (c) ADOPTER mode archives every legacy file's RAW BYTES first, under the sha256 directory name;
#   (d) IMMUTABILITY: re-archiving DIFFERENT bytes under an existing hash is refused (exit 2), while an
#       identical re-archive is idempotent;
#   (e) pointer parsing extracts Expected-successor / Coverage hints and a pointer is never written into
#       an archived payload;
#   (f) the unmatched list is COMPUTED (a predecessor with no ranked or pointed successor is listed).

def self_test():
    import io
    import shutil
    import tempfile
    from contextlib import redirect_stdout, redirect_stderr

    def quiet(fn, *a, **k):
        with redirect_stdout(io.StringIO()), redirect_stderr(io.StringIO()):
            try:
                return fn(*a, **k)
            except SystemExit as exc:
                return "raised SystemExit({!r})".format(exc.code)

    try:
        tmp = Path(tempfile.mkdtemp(prefix="aiqt-gen-crosswalk-selftest-"))
    except OSError as exc:
        print("SELF-TEST ERROR: no writable temporary directory: {}".format(exc), file=sys.stderr)
        return 2
    failures = []
    try:
        # (a) REPO mode generate + drift-clean + determinism.
        good = tmp / "good"
        (good / ".aiqt" / "core" / "migration").mkdir(parents=True)
        if quiet(run_repo, good, False) != 0:
            failures.append("REPO generate expected exit 0")
        if quiet(run_repo, good, True) != 0:
            failures.append("REPO regeneration expected drift-clean exit 0")
        first = (good / SCHEMA_REL).read_text(encoding="utf-8")
        quiet(run_repo, good, False)
        if (good / SCHEMA_REL).read_text(encoding="utf-8") != first:
            failures.append("REPO mode is not deterministic")

        # (b) mutated schema -> exit 1.
        (good / SCHEMA_REL).write_text(first + "# tamper\n", encoding="utf-8")
        if quiet(run_repo, good, True) != 1:
            failures.append("a mutated schema reference expected exit 1 (drift)")

        # (c) ADOPTER archive-first: raw bytes under the sha256 dir name.
        legacy = tmp / "legacy"
        legacy.mkdir()
        body = "Old obligation text.\n\nExpected-successor: succ.1\nCoverage: full\n"
        (legacy / "rule.md").write_text(body, encoding="utf-8")
        out = tmp / "adopt"
        succ = {"succ.1": "The successor obligation text.", "succ.2": "Unrelated."}
        if quiet(run_adopter, legacy, out, succ) != 0:
            failures.append("ADOPTER mode expected exit 0")
        digest = hashlib.sha256(body.encode()).hexdigest()
        payload = out / ".aiqt" / "archive" / digest / "payload"
        if not payload.is_file() or payload.read_bytes() != body.encode():
            failures.append("ADOPTER mode did not archive the raw legacy bytes under its sha256")
        # (e) a pointer line is present in the source but the archived payload is the RAW file, unchanged.
        if b"Expected-successor" not in payload.read_bytes():
            failures.append("the archived payload must be the raw file (pointers not stripped from it)")
        cand_text = (out / ".aiqt" / "migration" / "crosswalk.candidate.toml").read_text(encoding="utf-8")
        if 'semantic-verdict = ""' not in cand_text:
            failures.append("candidate mapping rows must carry EMPTY verdict fields (asserts nothing)")
        # fix #6: the 8.2-required owner is captured from the source fd and emitted on the archive-file row.
        if "owner = {}".format(os.getuid()) not in cand_text:
            failures.append("archive-file rows must carry the 8.2 owner captured from the source fd")
        # G-hardening: candidate predecessor rows now carry computable 7.2 spans (start-line/end-line).
        if "start-line = " not in cand_text or "end-line = " not in cand_text:
            failures.append("candidate predecessor rows must emit computable 7.2 spans (start-line/end-line)")

        # (d) immutability: differing re-archive refused; identical idempotent.
        archive_root = out / ".aiqt" / "archive"
        afd = os.open(str(archive_root), os.O_RDONLY | os.O_DIRECTORY)
        try:
            same = archive_file(afd, body.encode())
            if same != digest:
                failures.append("identical re-archive should be idempotent")
        except AdoptError:
            failures.append("identical re-archive should not be refused")
        # forge a differing payload under the same hash dir and confirm refusal
        forged = archive_root / digest / "payload"
        forged.write_bytes(b"tampered\n")
        try:
            archive_file(afd, body.encode())
            failures.append("re-archiving different bytes under an existing hash must be refused (exit 2)")
        except AdoptError:
            pass
        os.close(afd)

        # (fix #7) unique-per-call temp + no-overwrite publish: a fresh archive leaves NO leftover temp in
        # its entry dir, publishes the exact bytes, and a same-bytes re-archive is idempotent.
        fresh = b"a distinct archive payload for the temp/link test\n"
        fdig = hashlib.sha256(fresh).hexdigest()
        arc7 = tmp / "arc7"
        arc7.mkdir()
        afd7 = os.open(str(arc7), os.O_RDONLY | os.O_DIRECTORY)
        d1 = archive_file(afd7, fresh)
        d2 = archive_file(afd7, fresh)                     # same-bytes re-archive is idempotent
        os.close(afd7)
        if d1 != fdig or d2 != fdig:
            failures.append("archive_file must be content-addressed and idempotent")
        entry7 = arc7 / fdig
        if (entry7 / "payload").read_bytes() != fresh:
            failures.append("the published payload must be the exact archived bytes")
        leftover = [p.name for p in entry7.iterdir() if p.name != "payload"]
        if leftover:
            failures.append("archive_file must leave no temp files behind (found {})".format(leftover))

        # (B1) post-publish verification: a payload SUBSTITUTED between the no-overwrite publish link and
        # the digest re-check is refused (fail-closed), never reported as a clean publish. The substitution
        # is injected by wrapping os.link so that immediately AFTER the real link publishes our temp inode,
        # <entry>/payload is repointed at DIFFERENT bytes (a distinct regular file); the post-publish
        # inode/digest re-check must then raise AdoptError. Without the re-check a swap sails to false success.
        b1bytes = b"b1 post-publish payload verification test\n"
        b1dig = hashlib.sha256(b1bytes).hexdigest()
        b1arc = tmp / "b1arc"
        b1arc.mkdir()
        b1fd = os.open(str(b1arc), os.O_RDONLY | os.O_DIRECTORY)
        real_link = os.link

        def _link_then_swap(src, dst, **kw):
            real_link(src, dst, **kw)                      # the real no-overwrite publish of our temp inode
            entry = b1arc / b1dig                          # then substitute a different-inode payload
            (entry / "payload").unlink()
            (entry / "evil").write_bytes(b"a different payload than we wrote\n")
            real_link(str(entry / "evil"), str(entry / "payload"))

        os.link = _link_then_swap
        try:
            archive_file(b1fd, b1bytes)
            failures.append("B1: a payload substituted after the publish link must be refused (fail-closed)")
        except AdoptError:
            pass
        finally:
            os.link = real_link
            os.close(b1fd)

        # (f) unmatched computed: a predecessor with no overlap and no pointer is listed unmatched.
        legacy2 = tmp / "legacy2"
        legacy2.mkdir()
        (legacy2 / "x.md").write_text("zzz qqq wthismatchesnothing\n", encoding="utf-8")
        arc2 = tmp / "arc2"
        arc2.mkdir()
        afd2 = os.open(str(arc2), os.O_RDONLY | os.O_DIRECTORY)
        cand = build_candidates(legacy2, afd2, {})            # empty successor set -> nothing to map
        os.close(afd2)
        if not cand["unmatched"]:
            failures.append("a predecessor with no mappable successor must appear in the unmatched list")

        # (G8) a SYMLINKED payload under an existing hash dir is refused (a following read would have
        # accepted redirectable external bytes as if immutable).
        g8bytes = b"g8 archive immutability under a no-follow read\n"
        g8dig = hashlib.sha256(g8bytes).hexdigest()
        g8arc = tmp / "g8arc"
        (g8arc / g8dig).mkdir(parents=True)
        g8ext = tmp / "g8-external"
        g8ext.write_bytes(g8bytes)                            # external bytes that MATCH, so a follow would pass
        os.symlink(str(g8ext), str(g8arc / g8dig / "payload"))
        g8fd = os.open(str(g8arc), os.O_RDONLY | os.O_DIRECTORY)
        try:
            archive_file(g8fd, g8bytes)
            failures.append("G8: a symlinked archived payload must be refused (no-follow), not accepted")
        except AdoptError:
            pass
        os.close(g8fd)

        # (G9) durable hierarchy creation: run_adopter into a FRESH out dir completes without error and the
        # archive/migration dirs and entries are present (best-effort: the parent fsyncs are not observable).
        g9legacy = tmp / "g9-legacy"
        g9legacy.mkdir()
        (g9legacy / "r.md").write_text("A legacy obligation for the durability test.\n", encoding="utf-8")
        g9out = tmp / "g9" / "nested" / "out"                 # several missing hierarchy components
        if quiet(run_adopter, g9legacy, g9out, {}) != 0:
            failures.append("G9: run_adopter into a fresh nested out dir must exit 0")
        if not (g9out / ".aiqt" / "archive").is_dir():
            failures.append("G9: the archive hierarchy must be present after run_adopter")
        g9entries = list((g9out / ".aiqt" / "archive").iterdir()) if (g9out / ".aiqt" / "archive").is_dir() else []
        if not g9entries:
            failures.append("G9: at least one archive entry must be present after run_adopter")

        # (G8 ancestor) a symlinked .aiqt ANCESTOR in the OUTPUT tree cannot redirect the archive: the
        # no-follow ancestor walk refuses it and run_adopter fails CLOSED (exit 2), never writing the
        # archive through the link to an external directory. A target-following mkdir/open would have
        # created the archive under the external target instead.
        g8anc_out = tmp / "g8anc-out"
        g8anc_out.mkdir()
        g8anc_ext = tmp / "g8anc-external"
        g8anc_ext.mkdir()
        os.symlink(str(g8anc_ext), str(g8anc_out / ".aiqt"))
        if quiet(run_adopter, g9legacy, g8anc_out, {}) != 2:
            failures.append("G8: a symlinked .aiqt ancestor in the output tree must fail closed (exit 2)")
        if list(g8anc_ext.iterdir()):
            failures.append("G8: nothing must be written through the symlinked .aiqt ancestor")

        # (G9) an injected fsync failure on a newly-created hierarchy parent makes run_adopter FAIL CLOSED
        # (exit 2), never reporting success on a swallowed durability failure: the fsync OSError propagates
        # as an AdoptError rather than being discarded. Only the FIRST fsync (the first hierarchy parent) is
        # failed and every later fsync succeeds, so a discard bug would otherwise sail past it to a false
        # success (this isolates the swallow, not a blanket fsync outage).
        g9fail_out = tmp / "g9fail" / "out"
        real_fsync = os.fsync
        g9state = {"first": True}

        def _boom_once(fd):
            if g9state["first"]:
                g9state["first"] = False
                raise OSError("injected fsync failure")
            return real_fsync(fd)

        os.fsync = _boom_once
        try:
            g9rc = quiet(run_adopter, g9legacy, g9fail_out, {})
        finally:
            os.fsync = real_fsync
        if g9rc != 2:
            failures.append("G9: an injected fsync failure must make run_adopter fail closed (exit 2)")
    finally:
        shutil.rmtree(tmp, ignore_errors=True)

    if failures:
        print("SELF-TEST FAIL:")
        for f in failures:
            print("  - " + f)
        return 1
    print("SELF-TEST PASS: REPO mode generates the schema reference and regenerates drift-clean and "
          "deterministically (a mutation fails --check); ADOPTER mode archives every legacy file's RAW "
          "bytes FIRST under its sha256 (pointers are never stripped from the archived payload), emits "
          "candidate mapping rows with EMPTY verdict fields, refuses a differing re-archive under an "
          "existing hash while an identical one is idempotent, and computes the unmatched list. DISCLOSED: "
          "this tool does not claim section 8.6 pointer-carriage conformance; migration-state pointer "
          "carriage is deferred out of the VC-6 slice (to Step 7).")
    return 0


if __name__ == "__main__":
    sys.exit(main())
