"""Independent release-manifest verifier (VER-CORE 4.1/4.2/4.3, Section 12 step 2). Stdlib, fail-closed.

Verifies, against the anchored ownership map and the live tree, with no trust in generator output:
  1  schemas strict for ownership, manifest, order, references, renderers; dispositions and releases to
     Step-2 depth (top-level keys plus a minimal guard on any present row), the full per-row and per-kind
     schemas deferred to Step 4 (check_release_delta, where release and disposition rows are consumed);
  2  the build-time inversion assertion (completeness, no-strays, disjointness, exclusion cross-checks,
     concern-2 zero-tracked), recomputed via gen_manifest's validated loader (the house import-reuse
     pattern; the verdict is recomputed from inputs, never read from generated bytes);
  3  the ABSOLUTE-MINIMUM-CLASS table (declared HERE, the verifier; 4.2);
  4  release-version equals VERSION; genesis is boolean and consistent with releases.toml (2.5);
  5  exact SOURCES set equality plus per-row byte size and raw-byte SHA-256 (no decode, no normalize);
  6  filesystem semantics over the concern-1 extent: lstat every component; a symlink anywhere, a hard
     link (st_nlink > 1), a non-regular file, a case-fold or NFC/NFD collision, or CANNOT-EVALUATE is a
     FAIL, never a clean pass (4.3);
  7  the ARTIFACTS roster recomputed from the renderer declaration inputs; every digest re-hashed; the
     CLAUDE.md managed-block digest recomputed (bytes outside the block never affect the verdict);
  8  TREE digest recomputation; ROOT recomputed from the exact manifest bytes and byte-compared to
     .aiqt/release/root.txt; the announce snippet regenerated and byte-compared;
  9  the references registry schema with pipeline identity and the ALIAS GATE (5.3);
 10  the dispositions record schema (6.5), header-or-rows: the common mandatory fields, a known kind, a
     unique id, and no unknown top-level key (per-kind field validation deferred to Step 4, where used);
 11  the declared order record equals the operative ordering constants in gen_rules.py (TIER_FACETS,
     CIA_FACETS, apex prjint1), so the record cannot drift from operative code.

NOT here (named residue): the site/downloads recomputation is owned by those generators' own drift
gates in the same roster; adopter-side set-equality runs over the concern-3 extent per the
adopter-experience spec; the manifest detects ACCIDENT, not tamper (4.4).

  check_manifest.py [--root DIR]      the release-side gate
  check_manifest.py --self-test       synthetic fixtures assert every leg fires

Exit convention: 0 clean; 1 a well-formed disagreement (digest, size, set, TREE, ROOT, snippet,
artifact, managed-block, order-consistency drift); 2 malformed/unreadable input, an assertion or
schema violation, a minimum-class violation, a filesystem-semantics violation, or any cannot-evaluate.
"""
