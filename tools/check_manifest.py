# The verifier-carried ABSOLUTE-MINIMUM-CLASS table (4.2): first match wins; the final row is the
# category default. Strength order: pack-immutable > managed-block > manifest-self = derived >
# adopter-state = archive. The manifest itself must be EXACTLY manifest-self.
CLASS_STRENGTH = {"pack-immutable": 4, "managed-block": 3, "manifest-self": 2, "derived": 2,
                  "adopter-state": 1, "archive": 1}
MINIMUM_CLASSES = (
    (".aiqt/manifest.toml", "manifest-self", "exact"),
    ("CLAUDE.md", "managed-block", "min"),
    (".aiqt/release/**", "derived", "min"),
    ("site/downloads/**", "derived", "min"),
    (".aiqt/frozen.json", "derived", "min"),  # EN-8 write-scope frozen floor: a generated (derived) output,
    #                                           gen_manifest-emitted from the ownership classification, like
    #                                           the release/ and downloads/ generated outputs above.
    ("**", "pack-immutable", "min"),   # the category default: every other in-scope pack path
)

DISPOSITION_KINDS = {"behaviour-neutral", "strengthened", "default-correction", "class-change",
                     "version-impact", "renderer-semantics"}


def _min_for(path):
    for sel, minimum, mode in MINIMUM_CLASSES:
        if sel == "**" or path == sel or (sel.endswith("/**") and path.startswith(sel[:-2])):
            return minimum, mode
    raise AssertionError("unreachable: the '**' default row always matches")


def apply_minimums(classes):
    """FAIL (GateError -> exit 2) any assignment weaker than its declared minimum; binds every map at
    every release including genesis and first add (4.2). Shared with gen_manifest."""
    for path, cls in classes.items():
        minimum, mode = _min_for(path)
        if mode == "exact":
            if cls != minimum:
                raise gen_manifest.GateError("{}: class must be exactly {!r}, got {!r}".format(
                    path, minimum, cls))
        elif CLASS_STRENGTH[cls] < CLASS_STRENGTH[minimum]:
            raise gen_manifest.GateError("{}: class {!r} is weaker than the absolute minimum {!r}; the "
                                         "minimum is never dispositionable away".format(
                                             path, cls, minimum))


def load_manifest(root):
    """Use the shared pack grammar; map every refusal to GateError/exit 2."""
    from _opf_pack_manifest import parse_manifest, MAX_FILE_BYTES
    from _opf_adopt import VALID

    try:
        raw = read_source_bytes(root / gen_manifest.MANIFEST_REL, MAX_FILE_BYTES + 1)
    except (OSError, ValueError) as exc:
        raise gen_manifest.GateError(
            "cannot read the manifest ({})".format(exc)
        ) from exc

    document, result = parse_manifest(raw)
    if result.status != VALID:
        raise gen_manifest.GateError(
            "manifest {}: {}".format(result.status, "; ".join(result.findings))
        )
    return document


def walk_semantics(root, classes):
    """The 4.3 filesystem-semantics leg over the concern-1 extent: lstat every path component beneath
    root; any symlink, hard link, non-regular file, or unanswerable question is GateError (exit 2)."""
    checked_dirs = set()
    for path in classes:
        parts = path.split("/")
        cur = root
        for comp in parts[:-1]:
            cur = cur / comp
            if cur in checked_dirs:
                continue
            st = os.lstat(cur)  # OSError propagates to the caller's fail-closed map
            if stat.S_ISLNK(st.st_mode) or not stat.S_ISDIR(st.st_mode):
                raise gen_manifest.GateError("{}: intermediate {} is a symlink or not a directory"
                                             .format(path, cur.name))
            checked_dirs.add(cur)
        st = os.lstat(root / path)
        if stat.S_ISLNK(st.st_mode) or not stat.S_ISREG(st.st_mode):
            raise gen_manifest.GateError("{}: not a regular non-symlink file".format(path))
        if st.st_nlink > 1:
            raise gen_manifest.GateError("{}: hard link (st_nlink={})".format(path, st.st_nlink))


def check_order_record(root, findings):
    """Leg 11: the declared order record equals the operative constants (gen_rules.TIER_FACETS,
    CIA_FACETS, apex prjint1). Malformed record raises (exit 2); a well-formed disagreement is a
    finding (exit 1)."""
    import gen_rules
    try:
        data = load_toml(root / ".aiqt" / "core" / "order.toml")
    except (OSError, ValueError, tomllib.TOMLDecodeError) as exc:
        raise gen_manifest.GateError("cannot read order.toml ({})".format(exc))
    if data.get("format-version") != 1 or data.get("apex-corpus-id") != "prjint1":
        raise gen_manifest.GateError("order.toml: format-version 1 and apex-corpus-id 'prjint1' required")
    extra = set(data) - {"format-version", "apex-corpus-id", "precedence-tier", "presentation-order"}
    if extra:  # F-237: an unknown top-level key (e.g. a typo) is a schema FAIL, never silently tolerated.
        raise gen_manifest.GateError("order.toml: unknown top-level key(s): {}".format(
            ", ".join(sorted(extra))))
    try:
        declared = {int(t["rank"]): sorted(t["members"]) for t in data.get("precedence-tier", [])}
        for t in data.get("precedence-tier", []):
            if not isinstance(t.get("members-are-equal"), bool):
                raise gen_manifest.GateError("order.toml: members-are-equal must be a boolean")
    except (KeyError, TypeError, ValueError) as exc:
        raise gen_manifest.GateError("order.toml: a precedence-tier row is malformed ({})".format(exc))
    operative = {int(k): sorted(v) for k, v in gen_rules.TIER_FACETS.items()}
    if declared != operative:
        findings.append("order.toml precedence tiers disagree with the operative gen_rules.TIER_FACETS")
    pres = data.get("presentation-order", {})
    if sorted(pres.get("security-facets", [])) != sorted(gen_rules.CIA_FACETS):
        findings.append("order.toml security facets disagree with the operative gen_rules.CIA_FACETS")


def check_references(root):
    """Leg 9: the 5.3 registry schema and the alias gate. Violations raise (exit 2)."""
    try:
        data = load_toml(root / ".aiqt" / "core" / "references.toml")
    except (OSError, ValueError, tomllib.TOMLDecodeError) as exc:
        raise gen_manifest.GateError("cannot read references.toml ({})".format(exc))
    if data.get("format-version") != 1 or not isinstance(data.get("quorum"), int) \
            or isinstance(data.get("quorum"), bool) or data["quorum"] < 1:
        raise gen_manifest.GateError("references.toml: format-version 1 and integer quorum >= 1 required")
    extra = set(data) - {"format-version", "quorum", "reference"}
    if extra:  # F-237: an unknown top-level key (e.g. a `quroum` typo) is a schema FAIL.
        raise gen_manifest.GateError("references.toml: unknown top-level key(s): {}".format(
            ", ".join(sorted(extra))))
    pipelines = set()
    for row in data.get("reference", []):
        if set(row) != {"location", "retrieval-method", "derivation", "pipeline-id",
                        "independence-basis"}:
            raise gen_manifest.GateError("references.toml: a row's keys are not the exact 5.3 schema")
        if row["derivation"] not in ("independent", "mirror"):
            raise gen_manifest.GateError("references.toml: derivation must be independent|mirror")
        if row["derivation"] == "independent":
            if row["pipeline-id"] in pipelines:  # the ALIAS GATE: never silently count aliases once
                raise gen_manifest.GateError("references.toml: two independent entries share pipeline "
                                             "identity {!r}".format(row["pipeline-id"]))
            pipelines.add(row["pipeline-id"])
    # F-237 / spec 5.3: quorum must be SATISFIABLE. Quorum is counted over distinct independent pipeline
    # identities; a quorum exceeding the count available can never be met, so it is a schema FAIL, not a
    # verdict a later run silently fails.
    if data["quorum"] > len(pipelines):
        raise gen_manifest.GateError("references.toml: quorum {} exceeds the {} distinct independent "
                                     "pipeline identit(ies) available; an unsatisfiable quorum (5.3)"
                                     .format(data["quorum"], len(pipelines)))


def check_dispositions(root):
    """Leg 10: the 6.5 dispositions record schema (header-or-rows). Zero rows is valid, and is the whole
    Step-2 state (the record is header-only until the first dispositioned change). At Step 2 each row is
    checked for the COMMON mandatory fields, a known kind, a unique id, and no unknown top-level key.
    DEFERRED to Step 4 (the release-delta gate, spec 6.5), recorded not built here: PER-KIND field
    validation (each kind's own required fields, e.g. the default-correction evidence reference of 6.6),
    which the release-delta gate performs where disposition rows are first consumed. Violations raise
    (exit 2)."""
    try:
        data = load_toml(root / ".aiqt" / "core" / "dispositions.toml")
    except (OSError, ValueError, tomllib.TOMLDecodeError) as exc:
        raise gen_manifest.GateError("cannot read dispositions.toml ({})".format(exc))
    if data.get("format-version") != 1:
        raise gen_manifest.GateError("dispositions.toml: format-version must be exactly 1")
    extra = set(data) - {"format-version", "disposition"}
    if extra:  # F-237: an unknown top-level key is a schema FAIL, never silently tolerated.
        raise gen_manifest.GateError("dispositions.toml: unknown top-level key(s): {}".format(
            ", ".join(sorted(extra))))
    ids = set()
    for row in data.get("disposition", []):
        common = {"id", "release", "kind", "impact", "rationale"}
        if not common <= set(row):
            raise gen_manifest.GateError("dispositions.toml: a row is missing a mandatory field")
        if row["kind"] not in DISPOSITION_KINDS:
            raise gen_manifest.GateError("dispositions.toml: unknown kind {!r}".format(row["kind"]))
        if row["id"] in ids:
            raise gen_manifest.GateError("dispositions.toml: duplicate id {!r}".format(row["id"]))
        ids.add(row["id"])


def run(root, anchored=False):
    findings = []
    try:
        # 1 + 2 + 3: schemas, the inversion assertion, minimums (all recomputed; exit 2 on violation).
        exclusions, release, namespace, binary_set = gen_manifest.load_ownership(root)
        tracked = gen_manifest.git_tracked(root)
        classes, _ = gen_manifest.classify(tracked, exclusions, release, namespace, root)
        gen_manifest.cross_check_exclusions(root, exclusions)
        apply_minimums(classes)
        gen_manifest.check_output_modes(root)  # F-236: the four outputs are index-mode 100644 (defence in depth).
        manifest = load_manifest(root)

        # 4: version and genesis consistency.
        version = gen_manifest.read_version(root)
        if manifest["release-version"] != version:
            findings.append("manifest release-version {!r} does not equal VERSION {!r}".format(
                manifest["release-version"], version))
        if manifest["genesis"] != gen_manifest.read_genesis(root):
            raise gen_manifest.GateError("manifest genesis flag disagrees with the releases.toml row "
                                         "count (2.5); a genesis manifest requires a zero-row record")

        # 5: exact SOURCES set equality + raw-byte re-hash.
        expected = sorted(p for p, c in classes.items()
                          if p not in (gen_manifest.MANIFEST_REL, gen_manifest.ROOT_REL,
                                       gen_manifest.SNIPPET_REL) and c != "managed-block")
        declared = [r["path"] for r in manifest["sources"]]
        for missing in sorted(set(expected) - set(declared)):
            findings.append("SOURCES missing the tracked pack path {}".format(missing))
        for extra in sorted(set(declared) - set(expected)):
            findings.append("SOURCES lists {} which is not an expected member".format(extra))
        for row in manifest["sources"]:
            if row["path"] not in classes:
                continue  # already a finding above
            try:
                data = read_source_bytes(root / row["path"])  # a FIFO is refused, never blocks
            except OSError as exc:
                raise gen_manifest.GateError("cannot read SOURCES member {} ({})".format(row["path"], exc))
            if len(data) != row["bytes"] or hashlib.sha256(data).hexdigest() != row["sha256"]:
                findings.append("{}: bytes/sha256 disagree with the working tree".format(row["path"]))

        # 6: filesystem semantics (exit 2 on violation).
        walk_semantics(root, classes)

        # 7: artifacts recomputed from inputs.
        renderers = gen_manifest.load_renderers(root)
        expected_rows = gen_manifest.build_artifacts(root, classes, renderers)
        got = {(r.get("artifact-id"), r.get("path"), r.get("kind"), r.get("sha256"),
                r.get("block-id")) for r in manifest["artifacts"]}
        want = {(r.get("artifact-id"), r.get("path"), r.get("kind"), r.get("sha256"),
                 r.get("block-id")) for r in expected_rows}
        for row in sorted(want - got):
            findings.append("ARTIFACTS missing or drifted: {}".format(row[0]))
        for row in sorted(got - want):
            findings.append("ARTIFACTS lists an unexpected or stale row: {}".format(row[0]))

        # 8: TREE, ROOT, snippet recomputation.
        tree = hashlib.sha256("".join("{}\t{}\n".format(r["path"], r["sha256"])
                                      for r in manifest["sources"]).encode("utf-8")).hexdigest()
        if tree != manifest["tree-sha256"]:
            findings.append("tree-sha256 does not recompute from the SOURCES rows")
        try:
            manifest_raw = read_source_bytes(root / gen_manifest.MANIFEST_REL)
            root_disk = read_source_bytes(root / gen_manifest.ROOT_REL)
            snippet_disk = read_source_bytes(root / gen_manifest.SNIPPET_REL)
        except OSError as exc:
            raise gen_manifest.GateError("cannot read a derived release artifact ({})".format(exc))
        root_hex = hashlib.sha256(manifest_raw).hexdigest()
        if root_disk != "sha256:{}\n".format(root_hex).encode():
            findings.append("root.txt does not recompute from the manifest bytes")
        want_snippet = "aiqt-guardrails release {}\nroot sha256:{}\n".format(version, root_hex).encode()
        if snippet_disk != want_snippet:
            findings.append("announce-snippet.txt does not recompute from manifest plus version")

        # 9 + 10 + 11: the 5.3 registry, the 6.5 dispositions record, and the order record.
        check_references(root)
        check_dispositions(root)
        check_order_record(root, findings)

        if anchored:
            # 5.7 observed-run recording: deferred at this release (quorum default 1, anchor deferred).
            pass
    except gen_manifest.GateError as exc:
        print("error: {}; fail-closed".format(exc), file=sys.stderr)
        return 2
    except (OSError, UnicodeError, tomllib.TOMLDecodeError, ValueError, KeyError, TypeError) as exc:
        print("error: cannot evaluate ({}: {}); fail-closed".format(type(exc).__name__, exc),
              file=sys.stderr)
        return 2
    if findings:
        print("FAIL: {} finding(s)".format(len(findings)))
        for f in findings:
            print("  - " + f)
        return 1
    print("PASS: manifest verified: scope by inversion, {} sources set-equal and re-hashed, artifacts, "
          "tree, root, and snippet recomputed clean".format(len(manifest["sources"])))
    return 0


def main():
    args = sys.argv[1:]
    if "--self-test" in args:
        return self_test_main()
    root = repo_root()
    if "--root" in args:
        i = args.index("--root")
        if i + 1 >= len(args):
            print("usage: check_manifest.py [--root DIR] [--anchored] | --self-test", file=sys.stderr)
            return 2
        root = precheck_special_files(Path(args[i + 1]).resolve())
    return run(root, anchored="--anchored" in args)


