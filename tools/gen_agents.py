    def verified_rmtree(made, label, fail_list=None):
        # Every temporary-root removal is judged, never assumed: a removal error is recorded as
        # a failure, never suppressed, and the root must really be gone afterwards, so a removal
        # that reports no error yet leaves the root behind is a failure too, and so is a root
        # whose state root_presence cannot establish, before the removal or after it. Vector (f)
        # below drives a denied removal end to end, vector (g) a denied recovery removal, vector
        # (h) a removal that returns without deleting the root and without reporting any error,
        # and the cleanup helper vectors a root that cannot be inspected. fail_list: where a
        # failure lands; the matrix's own list by default (the cleanup helper vectors pass
        # their own, to judge the failure the helper records).
        sink = failures if fail_list is None else fail_list
        removal_errors = []
        present = root_presence(made)
        if isinstance(present, OSError):
            sink.append("{}: the state of the temporary root {} cannot be verified before its "
                        "removal: {}".format(label, made, present))
            return
        if present:
            shutil.rmtree(made, onexc=lambda _fn, pth, exc: removal_errors.append(
                "{}: {}".format(pth, exc)))
        if removal_errors:
            sink.append("{}: the temporary root {} was not fully removed: {}".format(
                label, made, "; ".join(removal_errors)))
            return
        present = root_presence(made)
        if isinstance(present, OSError):
            sink.append("{}: the state of the temporary root {} cannot be verified after its "
                        "removal: {}".format(label, made, present))
        elif present:
            sink.append("{}: the temporary root {} still exists although its removal "
                        "reported no error".format(label, made))

    def open_fds():
        """The open descriptors (the sentinel left out), or None when no trustworthy enumeration is
        available. A sentinel descriptor opened for this call must appear in the listing: one that
        omits it is incomplete and fails closed as None, exactly like an unlistable directory, so
        the accounting never trusts a listing shown to drop descriptors. A sentinel that cannot be
        opened (an unopenable /dev/null) is None too, and so is one whose close fails: that close
        is attempted exactly once, never blindly retried (after a failed close the descriptor's
        state is unknown, so a retry could close an unrelated descriptor), and either way the
        matrix still reaches its named NOT RUN failure and its cleanup rather than crashing past
        them. Residual: a partial listing that still holds the sentinel and happens to match its
        counterpart can hide a leak; the sentinel refutes a listing that drops it, it does not
        prove completeness."""
        try:
            sentinel = os.open(os.devnull, os.O_RDONLY)
        except OSError:
            return None  # no sentinel could be opened: fail closed, like an unlistable directory
        result = None
        close_failed = False
        try:
            for fd_dir in ("/proc/self/fd", "/dev/fd"):
                try:
                    names = os.listdir(fd_dir)
                except OSError:
                    continue
                if str(sentinel) in names:
                    result = sorted(name for name in names if name != str(sentinel))
                # The first listable directory decides either way: a listing that omits the
                # sentinel leaves result None, an incomplete listing never a partial accounting.
                break
        finally:
            try:
                os.close(sentinel)  # exactly once: a failed close is never blindly retried
            except OSError:
                close_failed = True
        if close_failed:
            return None  # the sentinel close failed: fail closed, like an unlistable directory
        return result

