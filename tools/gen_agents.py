def sort_key(fm):
    if fm["family"] == "aiqt":
        if fm.get("apex") is True:
            return (0, 0, 0, str(fm["slug"]))
        return (1, int(fm["tier"]), AIQT_FACET_ORDER.get(fm.get("facet", ""), 9), str(fm["slug"]))
    return (2, 0, CIA_FACET_ORDER.get(fm.get("facet", ""), 9), str(fm["slug"]))


def body_of(path):
    text = path.read_text(encoding="utf-8")
    end = text.find("\n---\n", 4)
    body = text[end + 5:].strip()
    if body.startswith("# "):        # demote the rule title to a section heading under the AGENTS.md H1
        body = "#" + body
    return body


def _read_list_bytes(path):
    """The one read of the must-deliver list's bytes, a module attribute so a self-test can inject an
    OSError here on every runner, including one where a mode-000 file stays readable."""
    return path.read_bytes()


def must_deliver_ids(core_dir):
    """The rule ids the must-deliver list (must-deliver.toml under core_dir, the .aiqt/core/ directory)
    names, as a frozenset. An absent list names none, so a tree without that policy (an adopter install, a
    synthetic fixture) keeps the plain AIQT order; tools/check_must_deliver.py is the gate that refuses an
    absent list. A list that is there but is not a regular file, cannot be read, or does not parse to
    [[rule]] rows with string ids is a ValueError or OSError (exit 2), never a fallback to an order that
    could move a listed rule past the cap. The rest of the schema is judged by check_must_deliver.py."""
    path = Path(core_dir) / Path(MUST_DELIVER_REL).name
    try:
        st = os.lstat(path)
    except FileNotFoundError:
        return frozenset()
    if not stat.S_ISREG(st.st_mode):
        raise ValueError("{} is not a regular file (a symlink, directory or special entry)".format(
            MUST_DELIVER_REL))
    try:
        data = tomllib.loads(_read_list_bytes(path).decode("utf-8"))
    # UnicodeDecodeError and TOMLDecodeError are ValueErrors; deep nesting is a RecursionError.
    except (ValueError, RecursionError, MemoryError) as exc:
        raise ValueError("{} does not parse ({})".format(MUST_DELIVER_REL, exc))
    rows = data.get("rule")
    if not isinstance(rows, list) or not all(isinstance(r, dict) and isinstance(r.get("id"), str) for r in rows):
        raise ValueError("{} must hold [[rule]] rows each with a string id".format(MUST_DELIVER_REL))
    return frozenset(r["id"] for r in rows)


def ordered_pairs(pairs, first=frozenset()):
    """(path, frontmatter) pairs in AGENTS.md order: the apex, then the rules whose corpus-id is in first
    (the must-deliver list), then every other rule, each group in sort_key order. The listed rules form
    the prefix after the apex by construction, so only their own text and the header move them."""
    def key(pf):
        aiqt = sort_key(pf[1])
        return (aiqt[0] != 0, str(pf[1].get("corpus-id")) not in first, aiqt)
    return sorted(pairs, key=key)


def ordered_bodies(corpus, first=frozenset()):
    """The rule bodies of a loaded corpus ([(path, frontmatter, rel)]) in ordered_pairs order."""
    return [body_of(src) for src, _fm in ordered_pairs(((src, fm) for src, fm, _ in corpus), first)]


def corpus_bodies(src_dir):
    """Load the corpus under src_dir and return its rule bodies in plain AIQT priority order (the
    reader gen_adapters.py shares; its adapters carry no must-deliver list)."""
    return ordered_bodies(load_corpus(src_dir))


def agents_bodies(src_dir):
    """Load the corpus under src_dir (.aiqt/core/rules/) and return its rule bodies in AGENTS.md order,
    the must-deliver list read from the directory above it (run()'s corpus reader for AGENTS.md)."""
    return ordered_bodies(load_corpus(src_dir), must_deliver_ids(Path(src_dir).parent))


def render(pairs):
    """The legacy AGENTS.md text for sorted (path, frontmatter) pairs; kept for existing importers."""
    return legacy_render(HEADER, [body_of(p) for p, _ in pairs])


def main():
    args = sys.argv[1:]
    if "--self-test" in args:
        return self_test_main()
    return run(repo_root(), "--check" in args, [(AGENTS_REL, HEADER)], "tools/gen_agents.py", agents_bodies)


